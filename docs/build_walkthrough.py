         "    'heading':  lambda t: psi0 + np.deg2rad(30.0) * (t >= 60.0),",
         "    'airspeed': lambda t: Va0 + 2.0 * (t >= 100.0),",
         "})",
         "ap = Autopilot(ac, ts, cmd)",
         "log = simulate_closed_loop(ac, ts, ap, t_end=200.0, dt_ctrl=0.02)",

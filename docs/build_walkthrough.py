def md(*lines: str) -> dict:
    return {
        "cell_type": "markdown",
        "metadata": {},
        "source": [l + ("" if l.endswith("\n") else "\n") for l in lines][:-1]
                  + [lines[-1]],
    }


def code(*lines: str) -> dict:
    return {
        "cell_type": "code",
        "metadata": {},
        "execution_count": None,
        "outputs": [],
        "source": [l + ("" if l.endswith("\n") else "\n") for l in lines][:-1]
                  + [lines[-1]],
    }


